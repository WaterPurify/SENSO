MOODS_BY_KEY: dict[str, Mood] = {m.key: m for m in MOODS}


def pick_verse(mood: Mood, day: date) -> Verse:
    """같은 날에는 같은 구절. 구절이 여러 개면 날마다 돌아가며."""
    return mood.verses[day.toordinal() % len(mood.verses)]


def find_verse(mood_key: str, ref: str) -> tuple[Mood, Verse] | None:
    """저장해 둔 카드를 다시 열 때. 데이터가 바뀌어 없으면 None."""
    mood = MOODS_BY_KEY.get(mood_key)
    if mood is None:
        return None
    for v in mood.verses:
        if v.ref == ref:
            return mood, v
    for m in MOODS:  # 구절이 다른 기분으로 옮겨졌을 때
        for v in m.verses:
            if v.ref == ref:
                return mood, v
    return None


